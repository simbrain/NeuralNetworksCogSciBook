"""Anatomy of a context window in a chat model with tools.

Everything the model sees is one token sequence. Special tokens (dark boxes)
mark who wrote each part. Gray segments were generated by the model.
"""
from style import new_fig, save, rbox, line, INK

FS = 8
ROWS = [
    # (special token, text, written by model?)
    ("<system>", "You are a helpful assistant. Tools: weather(city).", False),
    ("<user>", "Is it nice out in Merced?", False),
    ("<think>", "The user wants current weather. Call the tool.", True),
    ("<tool_call>", 'weather("Merced")', True),
    ("<tool_result>", '{"temp_f": 72, "sky": "sunny"}', False),
    ("<assistant>", "Yes, it's 72°F and sunny in Merced.", True),
    ("<user>", "Thanks! Should I bring a jacket tonight?", False),
    ("<assistant>", "█", True),
]


OUTPUTS = ['context_window']


def main():
    fig, ax = new_fig(6.5, 3.6)
    rh, gap, tw, bw = 0.34, 0.1, 1.35, 4.6
    for i, (tag, text, model) in enumerate(ROWS):
        y = -i * (rh + gap)
        rbox(ax, 0, y, tw, rh, tag, fc="0.25", ec="0.25", fs=FS - 1, family="monospace", color="white")
        rbox(ax, tw + 0.08, y, bw, rh, fc="0.88" if model else "white", lw=0.7)
        ax.text(tw + 0.2, y + rh / 2, text, ha="left", va="center", fontsize=FS,
                family="monospace" if tag in ("<tool_call>", "<tool_result>") else None)
    ytop, ybot = rh, -(len(ROWS) - 1) * (rh + gap)
    xr = tw + 0.08 + bw + 0.15
    line(ax, [xr, xr + 0.08, xr + 0.08, xr], [ytop, ytop, ybot, ybot])
    ax.text(xr + 0.18, (ytop + ybot) / 2, "one token\nsequence", ha="left", va="center", fontsize=FS)
    save(fig, "context_window")


if __name__ == "__main__":
    main()
